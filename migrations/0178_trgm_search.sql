-- 0178: пошук, що прощає одруківку (S35)
--
-- Заміряно на проді 2026-07-29:
--   ноутбук → 50    ноутбк     → 0
--   айфон   → 50    холодильнк → 0
--   пилосос → 50    ноутбуук   → 0
--
-- Транслітерація брендів працює (search.py), а от одна пропущена літера — і глухо.
-- `ILIKE '%…%'` не прощає нічого за побудовою: це підрядок, а не схожість.
--
-- pg_trgm розбиває рядок на трилітерні шматки й міряє перетин множин. «ноутбк» проти
-- «ноутбук»: спільних триграм досить, щоб similarity вийшла ~0.6 — тобто одна
-- пропущена літера перестає бути стіною.
--
-- ⚠ Це ЗАПАСНИЙ шлях, а не заміна. Основним лишається ILIKE: він точний, дешевий і
-- дає рівно те, що людина написала. Схожість вмикається лише тоді, коли точний
-- пошук не знайшов НІЧОГО — інакше «айфон» почав би приносити «айфон-чохол-тримач»
-- поперед самих айфонів.
CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- GIN по триграмах назви.
--
-- ⚠ УТОЧНЕНО ПІСЛЯ ЗАМІРУ (той самий день): цей індекс обслуговує НЕ схожість, а
-- основний `title ILIKE ANY(...)` — перевірено планом:
--     Bitmap Index Scan on ix_sp_title_trgm
--       Index Cond: (title ~~* ANY ('{%ноутбук%,%noutbuk%}'::text[]))
-- Тобто він прискорює саме той шлях, яким ходять усі вдалі пошуки.
--
-- Оператор word_similarity (`%>`), на якому стоїть запасний шлях, індексом НЕ
-- обслуговується — ні GIN, ні GiST (перевірено обидва, план лишається Seq Scan).
-- Це свідомо прийнято: запасний шлях вмикається тільки коли точний пошук дав нуль,
-- і коштує ~0.5 с на 59 445 рядках. Коли база виросте втричі, це доведеться
-- переглядати — але не раніше.
CREATE INDEX IF NOT EXISTS ix_sp_title_trgm
    ON store_product USING gin (title gin_trgm_ops);
